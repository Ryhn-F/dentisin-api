"""Generate Kaggle/Colab ``.ipynb`` files from the reviewable percent-format sources (``*_kaggle.py``).

    python kaggle/make_ipynb.py            # (re)write kaggle/*.ipynb
    python kaggle/make_ipynb.py --check    # exit 1 if any .ipynb is missing/out of date (used by tests)

The ``.py`` file is the source of truth (review, ruff); the ``.ipynb`` is a deterministic build
product (no outputs, no execution counts) so it can be uploaded to Kaggle ("File -> Import notebook").

Inlining: the lines between ``# >>> inline: <file>`` and ``# <<< inline`` (in the ``.py`` an import of that
module, so ruff/py_compile see valid code) are REPLACED in the ``.ipynb`` by the content of ``<file>`` (next to
the source). Used for ``bootstrap.py``: cell 1 must work before the pipeline code is on the machine.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
SOURCES = ("yolox_nano_kaggle.py", "mediapipe_ssd_kaggle.py")


INLINE_START = "# >>> inline: "
INLINE_END = "# <<< inline"


def inline_files(lines: list[str], base: Path) -> list[str]:
    out: list[str] = []
    skipping = False
    for ln in lines:
        if ln.startswith(INLINE_START):
            name = ln[len(INLINE_START):].strip()
            body = (base / name).read_text(encoding="utf-8").splitlines()
            out += [f"# >>> inlined from ml/detection/kaggle/{name} (generated by make_ipynb.py -- do not edit here)", *body,
                    f"# <<< end of {name}"]
            skipping = True
        elif ln.startswith(INLINE_END) and skipping:
            skipping = False
        elif not skipping:
            out.append(ln)
    if skipping:
        raise ValueError(f"unterminated {INLINE_START!r} block")
    return out


def split_cells(text: str, base: Path = HERE) -> list[dict[str, Any]]:
    cells: list[dict[str, Any]] = []
    kind: str | None = None
    title = ""
    buf: list[str] = []

    def flush() -> None:
        if kind is None:
            return
        lines = list(buf)
        while lines and not lines[-1].strip():
            lines.pop()
        if kind == "markdown":
            src = [ln[2:] if ln.startswith("# ") else ln.lstrip("#") for ln in lines]
            cells.append({"cell_type": "markdown", "metadata": {}, "source": _join(src)})
        else:
            src = ([f"# {title}"] if title else []) + inline_files(lines, base)
            cells.append({"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": _join(src)})

    for line in text.splitlines():
        if line.startswith("# %%"):
            flush()
            rest = line[4:].strip()
            kind, title, buf = ("markdown", "", []) if rest.startswith("[markdown]") else ("code", rest, [])
        elif kind is not None:
            buf.append(line)
    flush()
    return cells


def _join(lines: list[str]) -> list[str]:
    return [ln + "\n" for ln in lines[:-1]] + lines[-1:] if lines else []


def to_notebook(text: str, base: Path = HERE) -> dict[str, Any]:
    return {
        "cells": split_cells(text, base),
        # "kaggle" = the block Kaggle itself writes into exported notebooks (T4 + Internet); Kaggle MAY apply it on
        # import [PERLU VERIFIKASI] -- RUNBOOK §3 still has the owner check Accelerator/Internet by hand.
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}, "accelerator": "GPU",
                     "kaggle": {"accelerator": "nvidiaTeslaT4", "isGpuEnabled": True, "isInternetEnabled": True,
                                "language": "python", "sourceType": "notebook", "dataSources": []}},
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def render(src: Path) -> str:
    return json.dumps(to_notebook(src.read_text(encoding="utf-8"), src.parent), indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true")
    p.add_argument("--dir", type=Path, default=HERE)
    args = p.parse_args(argv)
    stale = []
    for name in SOURCES:
        src = args.dir / name
        dst = src.with_suffix(".ipynb")
        text = render(src)
        if args.check:
            if not dst.is_file() or dst.read_text(encoding="utf-8") != text:
                stale.append(dst.name)
        else:
            dst.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", dst)
    if stale:
        print("out of date (run python kaggle/make_ipynb.py):", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

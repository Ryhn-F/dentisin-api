"""YOLOX adapter: writes a YOLOX Exp file + COCO layout and launches YOLOX's own tools/train.py.

PARTLY UNTESTED HERE (no GPU / no torch in the base env): the pure helpers (Exp rendering, resume
discovery, command building) are unit-tested; :func:`train` and :func:`export_onnx` need torch +
YOLOX and run on Kaggle/Colab. YOLOX must be installed from a pinned git commit AFTER the
GPL-3.0 code removal (YOLOX issue #765 / PR #781, Oct 2021) -- see :data:`YOLOX_COMMIT`.

trainer_options (configs/yolox_nano.yaml):
- ``yolox_repo``: local clone of YOLOX at :data:`YOLOX_COMMIT` (never committed here).
- ``act``: ``silu`` (matches the COCO-pretrained weights) or ``relu`` (INT8-friendlier, see
  onnx2tf README "accuracy of the INT8 quantized model degrades"; pretrained weights then only
  partially match -- record it).
- ``work_dir``: scratch dir for resized training copies + COCO layout (NOT exported; /kaggle/tmp).
- ``max_side``: longest side of the training copies (default 832 = 2x the 416 input).
- ``output_dir``: where YOLOX writes checkpoints (default ``<run_dir>/yolox_outputs``; keep it in
  /kaggle/working so a committed notebook version preserves ``latest_ckpt.pth`` for resume).
- ``resume_from``: list of directories/globs searched for ``latest_ckpt.pth`` (e.g. a previous
  notebook version attached as input); ``auto`` resume also looks in ``output_dir``.
- ``time_budget_h``: stop the trainer after this many hours (Kaggle sessions end at ~12 h);
  the last ``latest_ckpt.pth`` is kept and the next session resumes.
"""

from __future__ import annotations

import glob
import subprocess
import sys
import time
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any

from trainers.base import MissingOptionalDependencyError, TrainContext, require

#: Megvii-BaseDetection/YOLOX main @ 2025-06-08 (Apache-2.0; after the GPL code removal of PR #781).
YOLOX_COMMIT = "6ddff4824372906469a7fae2dc3206c7aa4bbaee"
INSTALL_HINT = (f"git clone https://github.com/Megvii-BaseDetection/YOLOX && git -C YOLOX checkout {YOLOX_COMMIT} && "
                "pip install --no-deps -e YOLOX && pip install loguru tabulate pycocotools thop ninja psutil tensorboard")
ACTS = ("silu", "relu")
EXP_NAME = "dentis_yolox_nano_exp"

EXP_TEMPLATE = '''# Generated by ml/detection/trainers/yolox_adapter.py -- do not edit by hand.
import os
from yolox.exp import Exp as MyExp


class Exp(MyExp):
    def __init__(self):
        super().__init__()
        self.depth = 0.33
        self.width = 0.25
        self.act = "{act}"
        self.input_size = ({h}, {w})
        self.test_size = ({h}, {w})
        self.random_size = (10, 20)
        self.mosaic_scale = (0.5, 1.5)
        self.enable_mixup = False
        self.num_classes = {num_classes}
        self.max_epoch = {epochs}
        self.no_aug_epochs = {no_aug_epochs}
        self.basic_lr_per_img = {lr} / 64.0
        self.seed = {seed}
        self.data_num_workers = {workers}
        self.eval_interval = {eval_interval}
        self.save_history_ckpt = False
        self.output_dir = r"{output_dir}"
        self.data_dir = r"{data_dir}"
        self.train_ann = "instances_train.json"
        self.val_ann = "instances_val.json"
        self.exp_name = os.path.split(os.path.realpath(__file__))[1].split(".")[0]

    def get_model(self, sublinear=False):
        # Nano uses depthwise convs (mirrors exps/default/yolox_nano.py); act is configurable.
        from yolox.models import YOLOX, YOLOPAFPN, YOLOXHead
        import torch.nn as nn
        if getattr(self, "model", None) is None:
            in_channels = [256, 512, 1024]
            backbone = YOLOPAFPN(self.depth, self.width, in_channels=in_channels, depthwise=True, act=self.act)
            head = YOLOXHead(self.num_classes, self.width, in_channels=in_channels, depthwise=True, act=self.act)
            self.model = YOLOX(backbone, head)
        for m in self.model.modules():
            if isinstance(m, nn.BatchNorm2d):
                m.eps = 1e-3
                m.momentum = 0.03
        self.model.head.initialize_biases(1e-2)
        return self.model

    def get_dataset(self, cache=False, cache_type="ram"):
        from yolox.data import COCODataset, TrainTransform
        return COCODataset(data_dir=self.data_dir, json_file=self.train_ann, name="train",
                           img_size=self.input_size,
                           preproc=TrainTransform(max_labels=50, flip_prob=self.flip_prob, hsv_prob=self.hsv_prob),
                           cache=cache, cache_type=cache_type)

    def get_eval_dataset(self, **kwargs):
        from yolox.data import COCODataset, ValTransform
        return COCODataset(data_dir=self.data_dir, json_file=self.val_ann, name="val",
                           img_size=self.test_size, preproc=ValTransform(legacy=kwargs.get("legacy", False)))
'''


def options(ctx: TrainContext) -> dict[str, Any]:
    opts: dict[str, Any] = dict(ctx.cfg.get("trainer_options", {}))
    act = opts.get("act", "silu")
    if act not in ACTS:
        raise ValueError(f"trainer_options.act must be one of {ACTS}, got {act!r}")
    opts["act"] = act
    opts.setdefault("output_dir", str(ctx.run_dir / "yolox_outputs"))
    opts.setdefault("work_dir", str(ctx.run_dir / "work"))
    opts.setdefault("max_side", 832)
    opts.setdefault("workers", 4)
    opts.setdefault("eval_interval", 10)
    return opts


def render_exp(ctx: TrainContext, data_dir: Path, opts: Mapping[str, Any] | None = None) -> str:
    o = options(ctx) if opts is None else opts
    w, h = ctx.cfg["model"]["input_size"]
    t = ctx.cfg["train"]
    return EXP_TEMPLATE.format(
        h=h, w=w, num_classes=len(ctx.cfg["data"]["classes"]), epochs=t["epochs"], no_aug_epochs=min(15, max(1, t["epochs"] // 10)),
        lr=t["learning_rate"], seed=ctx.seed, data_dir=data_dir.as_posix(), act=o["act"], workers=int(o["workers"]),
        eval_interval=int(o["eval_interval"]), output_dir=Path(str(o["output_dir"])).as_posix(),
    )


def find_resume_checkpoint(search: Iterable[Path], name: str = "latest_ckpt.pth") -> Path | None:
    """Newest ``name`` (by mtime, then path) under any of ``search`` (dirs searched recursively)."""
    found: list[Path] = []
    for root in search:
        if root.is_file() and root.name == name:
            found.append(root)
        elif root.is_dir():
            found += [p for p in root.rglob(name) if p.is_file()]
    if not found:
        return None
    return max(found, key=lambda p: (p.stat().st_mtime, str(p)))


def build_command(exp_path: Path, ctx: TrainContext, opts: Mapping[str, Any], *, resume: Path | None,
                  python: str = sys.executable) -> list[str]:
    cmd = [python, "tools/train.py", "-f", str(exp_path), "-d", str(opts.get("devices", 1)), "-b", str(ctx.cfg["train"]["batch_size"])]
    if opts.get("fp16", True):
        cmd.append("--fp16")
    if resume is not None:
        cmd += ["--resume", "-c", str(resume)]
    elif ctx.cfg["model"].get("pretrained"):
        cmd += ["-c", str(ctx.cfg["model"]["pretrained"])]
    return cmd


def resume_candidates(opts: Mapping[str, Any]) -> list[Path]:
    roots: list[Path] = [Path(str(opts["output_dir"]))]
    extra = opts.get("resume_from") or []
    for item in [extra] if isinstance(extra, str) else extra:
        roots += [Path(m) for m in sorted(glob.glob(str(item)))] if any(ch in str(item) for ch in "*?[") else [Path(str(item))]
    return roots


def train(ctx: TrainContext) -> dict[str, Any]:  # pragma: no cover - needs torch + YOLOX + GPU
    require("torch", "Kaggle/Colab kernels ship torch; locally: uv sync --extra train")
    require("yolox", INSTALL_HINT)
    import shutil

    from canonical import read_jsonl
    from convert_annotations import load_split_assignments, partition, resized_copy, write_coco_layout

    opts = options(ctx)
    repo = Path(opts.get("yolox_repo", ""))
    if not (repo / "tools" / "train.py").is_file():
        raise MissingOptionalDependencyError(f"YOLOX repo not found at {repo!s}; set trainer_options.yolox_repo")
    if ctx.images_root is None:
        raise MissingOptionalDependencyError("data.images_root is required for training")
    work = Path(str(opts["work_dir"]))
    data_dir = work / "data_yolox"
    parts = partition(read_jsonl(ctx.canonical), load_split_assignments(ctx.splits))
    for split in ("train", "val"):
        small = resized_copy(parts[split], ctx.images_root, work / "images", max_side=int(opts["max_side"]))
        write_coco_layout(small, data_dir, layout="yolox", split=split, images_root=work / "images", link=True)
    out_dir = Path(str(opts["output_dir"]))
    exp_dir = out_dir / EXP_NAME
    exp_dir.mkdir(parents=True, exist_ok=True)
    exp_path = ctx.run_dir / f"{EXP_NAME}.py"
    exp_path.write_text(render_exp(ctx, data_dir, opts), encoding="utf-8")
    resume = find_resume_checkpoint(resume_candidates(opts)) if opts.get("resume", "auto") == "auto" else None
    if resume is not None and resume.parent != exp_dir:
        shutil.copy2(resume, exp_dir / "latest_ckpt.pth")
        resume = exp_dir / "latest_ckpt.pth"
    cmd = build_command(exp_path, ctx, opts, resume=resume)
    budget = opts.get("time_budget_h")
    started = time.time()
    status = "completed"
    try:
        subprocess.run(cmd, cwd=repo, check=True, timeout=None if budget is None else float(budget) * 3600)
    except subprocess.TimeoutExpired:
        status = "time_budget_reached_resume_next_session"
    return {"command": cmd, "exp_file": str(exp_path), "status": status, "resumed_from": None if resume is None else str(resume),
            "hours": round((time.time() - started) / 3600, 3), "checkpoint_dir": str(exp_dir),
            "best_ckpt": str(exp_dir / "best_ckpt.pth"), "latest_ckpt": str(exp_dir / "latest_ckpt.pth"),
            "note": "Export with trainers.yolox_adapter.export_onnx (decode_in_inference=False)."}


def export_onnx(exp_file: Path, ckpt: Path, out: Path, *, opset: int = 13, raw_logits: bool = True) -> dict[str, Any]:  # pragma: no cover
    """YOLOX checkpoint -> ONNX with RAW head output [1, N, 5+C], no grid decode; with ``raw_logits`` (default)
    obj/cls are logits (config ``decode.sigmoid_applied: false``). The app decodes per DECODE_SPEC §3.1.
    Mirrors YOLOX tools/export_onnx.py without --decode_in_inference. Needs torch + YOLOX + onnx."""
    torch = require("torch", "pip install torch")
    require("yolox", INSTALL_HINT)
    from torch import nn
    from yolox.exp import get_exp
    from yolox.models.network_blocks import SiLU
    from yolox.utils import replace_module

    exp = get_exp(str(exp_file), None)
    model = exp.get_model()
    state = torch.load(str(ckpt), map_location="cpu", weights_only=False)  # own/YOLOX ckpt (numpy scalars; torch>=2.6 default)
    model.load_state_dict(state.get("model", state))
    model = replace_module(model, nn.SiLU, SiLU)  # export-friendly SiLU, as upstream export_onnx.py
    model.head.decode_in_inference = False
    model.eval()
    h, w = exp.test_size
    dummy = torch.zeros(1, 3, h, w)
    out.parent.mkdir(parents=True, exist_ok=True)
    torch.onnx.export(model, dummy, str(out), input_names=["images"], output_names=["output"], opset_version=opset, dynamo=False)
    with torch.no_grad():
        shape = list(model(dummy).shape)
    stripped = strip_head_sigmoid(out) if raw_logits else 0
    if raw_logits and stripped != 2 * len(model.head.strides):
        raise RuntimeError(f"expected {2 * len(model.head.strides)} head Sigmoid nodes (obj+cls per level), stripped {stripped}")
    return {"onnx": str(out), "input": [1, 3, h, w], "output_shape": shape, "opset": opset, "act": getattr(exp, "act", "silu"),
            "head_sigmoid_stripped": stripped, "sigmoid_applied": not raw_logits}


def strip_head_sigmoid(onnx_path: Path) -> int:  # pragma: no cover - needs onnx (proven on a tiny graph, see WEIGHT_LICENSES §3.1)
    """Remove the YOLOX head's obj/cls Sigmoid nodes (those consumed ONLY by Concat) so the model outputs raw
    logits (labels.json ``sigmoid_applied: false``; the app applies the sigmoid, DECODE_SPEC §3.1).

    Why: onnx2tf 2.6.9's default flatbuffer_direct INT8 path rejects LOGISTIC outputs whose calibrated scale is
    not 1/256 (proven locally 2026-10-10), and probabilities share one int8 scale with box offsets in the raw
    tensor. SiLU's Sigmoid nodes feed Mul and are left untouched."""
    onnx = require("onnx", "pip install onnx")
    model = onnx.load(str(onnx_path))
    g = model.graph
    consumers: dict[str, list[Any]] = {}
    for n in g.node:
        for i in n.input:
            consumers.setdefault(i, []).append(n)
    outputs = {o.name for o in g.output}
    drop = [n for n in g.node if n.op_type == "Sigmoid" and n.output[0] not in outputs
            and consumers.get(n.output[0]) and all(c.op_type == "Concat" for c in consumers[n.output[0]])]
    for n in drop:
        for c in consumers[n.output[0]]:
            for k, name in enumerate(c.input):
                if name == n.output[0]:
                    c.input[k] = n.input[0]
        g.node.remove(n)
    onnx.checker.check_model(model)
    onnx.save(model, str(onnx_path))
    return len(drop)


def expected_rows(input_size: Sequence[int], strides: Sequence[int] = (8, 16, 32)) -> int:
    w, h = input_size
    return sum((w // s) * (h // s) for s in strides)

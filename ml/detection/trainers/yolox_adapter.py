"""YOLOX adapter: writes a YOLOX Exp file + COCO layout and launches YOLOX's own tools/train.py.

UNTESTED HERE. YOLOX must be installed from a pinned git commit (trainer_options.yolox_repo).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from typing import Any

from trainers.base import MissingOptionalDependencyError, TrainContext, require

INSTALL_HINT = "git clone https://github.com/Megvii-BaseDetection/YOLOX && pip install -v -e YOLOX (pinned commit)"

EXP_TEMPLATE = '''# Generated by ml/detection/trainers/yolox_adapter.py -- do not edit by hand.
import os
from yolox.exp import Exp as MyExp


class Exp(MyExp):
    def __init__(self):
        super().__init__()
        self.depth = 0.33
        self.width = 0.25
        self.input_size = ({h}, {w})
        self.test_size = ({h}, {w})
        self.random_size = (10, 20)
        self.mosaic_scale = (0.5, 1.5)
        self.enable_mixup = False
        self.num_classes = {num_classes}
        self.max_epoch = {epochs}
        self.basic_lr_per_img = {lr} / 64.0
        self.seed = {seed}
        self.data_dir = r"{data_dir}"
        self.train_ann = "instances_train.json"
        self.val_ann = "instances_val.json"
        self.exp_name = os.path.split(os.path.realpath(__file__))[1].split(".")[0]

    def get_model(self, sublinear=False):
        # Nano uses depthwise convs (mirrors exps/default/yolox_nano.py).
        from yolox.models import YOLOX, YOLOPAFPN, YOLOXHead
        import torch.nn as nn
        if getattr(self, "model", None) is None:
            in_channels = [256, 512, 1024]
            backbone = YOLOPAFPN(self.depth, self.width, in_channels=in_channels, depthwise=True)
            head = YOLOXHead(self.num_classes, self.width, in_channels=in_channels, depthwise=True)
            self.model = YOLOX(backbone, head)
        for m in self.model.modules():
            if isinstance(m, nn.BatchNorm2d):
                m.eps = 1e-3
                m.momentum = 0.03
        self.model.head.initialize_biases(1e-2)
        return self.model

    def get_dataset(self, cache=False, cache_type="ram"):
        from yolox.data import COCODataset, TrainTransform
        return COCODataset(data_dir=self.data_dir, json_file=self.train_ann, name="train",
                           img_size=self.input_size,
                           preproc=TrainTransform(max_labels=50, flip_prob=self.flip_prob, hsv_prob=self.hsv_prob),
                           cache=cache, cache_type=cache_type)

    def get_eval_dataset(self, **kwargs):
        from yolox.data import COCODataset, ValTransform
        return COCODataset(data_dir=self.data_dir, json_file=self.val_ann, name="val",
                           img_size=self.test_size, preproc=ValTransform(legacy=kwargs.get("legacy", False)))
'''


def render_exp(ctx: TrainContext, data_dir: Path) -> str:
    w, h = ctx.cfg["model"]["input_size"]
    t = ctx.cfg["train"]
    return EXP_TEMPLATE.format(
        h=h, w=w, num_classes=len(ctx.cfg["data"]["classes"]), epochs=t["epochs"],
        lr=t["learning_rate"], seed=ctx.seed, data_dir=data_dir.as_posix(),
    )


def train(ctx: TrainContext) -> dict[str, Any]:  # pragma: no cover - needs torch + YOLOX
    require("torch", "uv sync --extra train")
    require("yolox", INSTALL_HINT)
    from canonical import read_jsonl
    from convert_annotations import load_split_assignments, partition, write_coco_layout

    opts = ctx.cfg.get("trainer_options", {})
    repo = Path(opts.get("yolox_repo", ""))
    if not (repo / "tools" / "train.py").is_file():
        raise MissingOptionalDependencyError(f"YOLOX repo not found at {repo!s}; set trainer_options.yolox_repo")
    data_dir = ctx.run_dir / "data_yolox"
    parts = partition(read_jsonl(ctx.canonical), load_split_assignments(ctx.splits))
    for split in ("train", "val"):
        write_coco_layout(parts[split], data_dir, layout="yolox", split=split, images_root=ctx.images_root)
    exp_path = ctx.run_dir / "dentis_yolox_nano_exp.py"
    exp_path.write_text(render_exp(ctx, data_dir), encoding="utf-8")
    cmd = [sys.executable, "tools/train.py", "-f", str(exp_path), "-d", str(opts.get("devices", 1)),
           "-b", str(ctx.cfg["train"]["batch_size"])]
    if opts.get("fp16", True):
        cmd.append("--fp16")
    if ctx.cfg["model"].get("pretrained"):
        cmd += ["-c", str(ctx.cfg["model"]["pretrained"])]
    subprocess.run(cmd, cwd=repo, check=True)
    return {"command": cmd, "exp_file": str(exp_path),
            "note": "Checkpoints are under YOLOX_outputs/ in the YOLOX repo; export with tools/export_onnx.py."}

def resume_candidates(opts: Mapping[str, Any]) -> list[Path]:
    roots: list[Path] = [Path(str(opts["output_dir"]))]
    extra = opts.get("resume_from") or []
    for item in [extra] if isinstance(extra, str) else extra:
        roots += [Path(m) for m in sorted(glob.glob(str(item)))] if any(ch in str(item) for ch in "*?[") else [Path(str(item))]
    return roots


#: Files carried over from a previous session's checkpoint dir (best_ckpt.pth: the best epoch may be in that session).
RESUME_FILES = ("latest_ckpt.pth", "best_ckpt.pth")
#: loguru's ``@logger.catch`` message: YOLOX tools/train.py wraps main() with it, so a crash still EXITS WITH CODE 0.
CAUGHT_ERROR = "An error has been caught in function"


def copy_resume_files(resume: Path, exp_dir: Path) -> list[str]:
    """Copy ``latest_ckpt.pth`` (+ ``best_ckpt.pth`` when present) from a previous session into ``exp_dir``."""
    import shutil

    copied = []
    for name in RESUME_FILES:
        src = resume if name == "latest_ckpt.pth" else resume.parent / name
        dst = exp_dir / name
        if src.is_file() and src.resolve() != dst.resolve():
            shutil.copy2(src, dst)
            copied.append(name)
    return copied


def caught_errors(log: Path, offset: int = 0) -> list[str]:
    """Error blocks that loguru printed into YOLOX's ``train_log.txt`` after byte ``offset`` (this session only)."""
    if not log.is_file():
        return []
    with log.open("rb") as fh:
        fh.seek(offset)
        text = fh.read().decode("utf-8", errors="replace")
    blocks = []
    for part in text.split(CAUGHT_ERROR)[1:]:
        lines = [ln for ln in part.splitlines() if ln.strip()]
        blocks.append("\n".join([CAUGHT_ERROR + (lines[0] if lines else ""), *lines[-12:]]))
    return blocks


def checkpoint_epoch(path: Path, load: Callable[[Path], Any] | None = None) -> int | None:
    """``start_epoch`` (= epochs completed) stored in a YOLOX checkpoint; None if missing or unreadable (corrupt)."""
    if not path.is_file():
        return None
    try:
        if load is None:
            import torch

            ckpt = torch.load(str(path), map_location="cpu", weights_only=False)  # own checkpoint (numpy scalars)
        else:
            ckpt = load(path)
        return int(ckpt["start_epoch"])
    except Exception as exc:  # truncated file (killed mid-save), wrong format
        print(f"WARNING: cannot read {path.name}: {type(exc).__name__}: {exc}", flush=True)
        return None


def _mtime(p: Path) -> float | None:
    try:
        return p.stat().st_mtime
    except OSError:
        return None


class TrainerStalled(RuntimeError):
    """YOLOX wrote nothing to train_log.txt for ``stall_s`` seconds (a hang, e.g. in a DataLoader worker or an eval)."""


def _log_size(log: Path) -> int:
    try:
        return log.stat().st_size
    except OSError:
        return -1


def last_log_line(log: Path, tail_bytes: int = 4096) -> str:
    """Last non-empty line of YOLOX's train_log.txt (progress line: 'epoch: 3/150, iter: 40/137 ...'), '' if none."""
    try:
        with log.open("rb") as fh:
            fh.seek(0, os.SEEK_END)
            fh.seek(max(0, fh.tell() - tail_bytes))
            text = fh.read().decode("utf-8", errors="replace")
    except OSError:
        return ""
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    return lines[-1][:220] if lines else ""


def process_report(pid: int, run: Callable[..., Any] = subprocess.run) -> str:
    """What a hung trainer looks like from outside: GPU load/memory (a busy GPU = a stuck kernel; idle = a CPU/data hang) and
    the state of every process in its session (D = blocked on I/O, Z = dead worker, wchan = what it waits for)."""
    parts = []
    for title, cmd in (("nvidia-smi", ["nvidia-smi", "--query-gpu=utilization.gpu,memory.used,memory.total,temperature.gpu,clocks.sm,power.draw",
                                       "--format=csv"]),
                       ("processes of the trainer's session", ["ps", "--sid", str(pid), "-o", "pid,ppid,stat,pcpu,pmem,etime,wchan:24,args"])):
        try:
            res = run(cmd, capture_output=True, text=True, check=False, timeout=30)
            parts.append(f"[{title}]\n{(res.stdout or res.stderr or '').strip()}")
        except (OSError, subprocess.SubprocessError) as exc:
            parts.append(f"[{title}] unavailable: {type(exc).__name__}")
    return "\n".join(parts)


def _dump_stacks(proc: Any, sleep: Callable[[float], None], log: Path | None = None,
                 run: Callable[..., Any] = subprocess.run) -> None:
    """Ask the (hung) trainer for a Python traceback of all its threads (faulthandler.register(SIGUSR1) in the Exp, which
    writes ``stacks.txt`` next to ``train_log.txt``), print it with :func:`process_report`, and keep both in
    ``stall_report.txt`` there so they come back with the downloaded outputs."""
    import signal

    pid = getattr(proc, "pid", None)
    if sys.platform == "win32" or pid is None or not hasattr(signal, "SIGUSR1"):
        return
    print(f"--- trainer stalled: Python stacks of pid {pid} (faulthandler) ---", flush=True)
    stacks = log.with_name("stacks.txt") if log is not None else None
    before = stacks.stat().st_size if stacks is not None and stacks.is_file() else 0
    with contextlib.suppress(OSError):
        os.kill(int(pid), signal.SIGUSR1)
        sleep(5.0)
    text = ""
    if stacks is not None and stacks.is_file():
        with stacks.open("rb") as fh:
            fh.seek(before)
            text = fh.read().decode("utf-8", errors="replace")
    stacks_text = text.strip() or "(no Python stacks: the Exp could not register faulthandler)"
    report = f"{stacks_text}\n\n{process_report(int(pid), run)}"
    print(report, flush=True)
    if log is not None:
        with contextlib.suppress(OSError), log.with_name("stall_report.txt").open("a", encoding="utf-8") as fh:
            fh.write(f"=== {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())} pid {pid} ===\n{report}\n")


def _stop(proc: Any, grace_s: float = 60.0) -> None:
    """Terminate the trainer and its dataloader workers (own process group on POSIX)."""
    import signal

    if proc.poll() is not None:
        return
    try:
        if sys.platform != "win32":
            os.killpg(proc.pid, signal.SIGTERM)
        else:
            proc.terminate()
        proc.wait(timeout=grace_s)
    except Exception:
        with contextlib.suppress(Exception):
            if sys.platform != "win32":
                os.killpg(proc.pid, signal.SIGKILL)
            else:
                proc.kill()
            proc.wait(timeout=grace_s)


def run_with_budget(cmd: Sequence[str], *, cwd: Path, env: Mapping[str, str], budget_s: float | None, watch: Path,
                    grace_s: float = 1800.0, settle_s: float = 15.0, poll_s: float = 5.0,
                    log: Path | None = None, stall_s: float | None = 1800.0, tail_every_s: float = 60.0,
                    popen: Callable[..., Any] = subprocess.Popen, clock: Callable[[], float] = time.time,
                    sleep: Callable[[float], None] = time.sleep) -> tuple[int | None, bool]:
    """Run the trainer; when ``budget_s`` is used up, stop it RIGHT AFTER its next ``latest_ckpt.pth`` write (epoch
    boundary + ``settle_s``), or after ``grace_s`` more seconds at the latest. Killing at a random moment (the old
    ``subprocess.run(timeout=...)``) could truncate the checkpoint the next session resumes from.
    Returns (exit code or None if stopped by us, stopped_for_budget)."""
    proc = popen(list(cmd), cwd=str(cwd), env=dict(env), start_new_session=sys.platform != "win32")
    started = clock()
    mark: float | None = None
    stop_at: float | None = None
    last_size, last_change, last_tail = _log_size(log) if log is not None else -1, started, started
    try:
        while True:
            rc = proc.poll()
            if rc is not None:
                return int(rc), False
            now = clock()
            if log is not None:
                size = _log_size(log)
                if size != last_size:
                    last_size, last_change = size, now
                if now - last_tail >= tail_every_s:  # YOLOX's own progress lines never reach the notebook output
                    last_tail = now
                    print(f"  [yolox {now - started:.0f}s] {last_log_line(log) or '(train_log.txt still empty)'}", flush=True)
                if stall_s is not None and stop_at is None and now - last_change >= stall_s:
                    line = last_log_line(log)
                    _dump_stacks(proc, sleep, log)
                    _stop(proc)
                    raise TrainerStalled(
                        f"YOLOX wrote nothing to train_log.txt for {stall_s / 60:.0f} min (after {now - started:.0f}s) -- "
                        f"a hang, not slow training. Last line: {line!r}. Stopped it instead of burning the session. "
                        "Try workers: 0 (config trainer_options) and look at the lines above; report them.")
            if budget_s is not None and stop_at is None and now - started >= budget_s:
                mark, stop_at = _mtime(watch), now + grace_s
                print(f"time budget reached ({budget_s / 3600:.2f} h): stopping after the next epoch checkpoint "
                      f"(at most {grace_s / 60:.0f} min) ...", flush=True)
            if stop_at is not None:
                changed = _mtime(watch) is not None and _mtime(watch) != mark
                if changed:
                    sleep(settle_s)  # let torch.save finish (and an eval epoch's best_ckpt copy start/finish)
                if changed or now >= stop_at:
                    _stop(proc)
                    return None, True
            sleep(poll_s)
    except BaseException:  # KeyboardInterrupt from the notebook: do not leave a GPU-holding orphan behind
        _stop(proc, grace_s=10.0)
        raise


#: Failures worth an automatic resume: a stall or a DataLoader that timed out (a hang, not a bug in our setup).
RETRIABLE_MARKERS = ("timed out", "DataLoader worker")


def is_retriable(exc: BaseException) -> bool:
    return isinstance(exc, TrainerStalled) or any(m in str(exc) for m in RETRIABLE_MARKERS)


def supervise(run_once: Callable[[int], Any], *, max_restarts: int, log: Callable[[str], None] = print) -> tuple[Any, list[dict[str, Any]]]:
    """Run ``run_once(attempt)``; after a retriable hang start it again (the caller resumes from ``latest_ckpt.pth``)
    up to ``max_restarts`` times. Other errors, and the last hang, propagate. Returns (result, restart records)."""
    restarts: list[dict[str, Any]] = []
    attempt = 0
    while True:
        try:
            return run_once(attempt), restarts
        except Exception as exc:
            if attempt >= max_restarts or not is_retriable(exc):
                raise
            restarts.append({"attempt": attempt, "reason": f"{type(exc).__name__}: {str(exc)[:300]}"})
            log(f"!!! trainer hang ({type(exc).__name__}) -> automatic restart {attempt + 1}/{max_restarts} from latest_ckpt.pth")
            attempt += 1


def outcome(*, rc: int | None, stopped: bool, errors: Sequence[str], epoch: int | None, max_epoch: int) -> str:
    """Status of a YOLOX run or a RuntimeError with the reason (never "completed" on a crash hidden by exit code 0)."""
    if errors:
        raise RuntimeError("YOLOX training crashed (tools/train.py exits with code 0 on errors; from train_log.txt):\n"
                           + "\n---\n".join(errors[-2:]))
    if epoch is None:
        raise RuntimeError("no readable latest_ckpt.pth after training (crashed before the first epoch ended, or the "
                           "checkpoint is truncated) -- see the log above")
    if stopped:
        return "completed" if epoch >= max_epoch else "time_budget_reached_resume_next_session"
    if rc not in (0, None):
        raise RuntimeError(f"YOLOX tools/train.py exited with code {rc} after epoch {epoch}/{max_epoch} -- see the log above")
    if epoch < max_epoch:
        raise RuntimeError(f"YOLOX stopped after epoch {epoch} of {max_epoch} without a time-budget stop and without "
                           "a logged error (killed? out of memory?) -- see the log above")
    return "completed"


def train(ctx: TrainContext) -> dict[str, Any]:  # pragma: no cover - needs torch + YOLOX (+ GPU; CPU in local_simulate)
    require("torch", "Kaggle/Colab kernels ship torch; locally: uv sync --extra train")
    require("yolox", INSTALL_HINT)
    from canonical import read_jsonl
    from convert_annotations import load_split_assignments, partition, resized_copy, write_coco_layout

    opts = options(ctx)
    repo = Path(opts.get("yolox_repo", ""))
    if not (repo / "tools" / "train.py").is_file():
        raise MissingOptionalDependencyError(f"YOLOX repo not found at {repo!s}; set trainer_options.yolox_repo")
    if ctx.images_root is None:
        raise MissingOptionalDependencyError("data.images_root is required for training")
    work = Path(str(opts["work_dir"]))
    data_dir = work / "data_yolox"
    parts = partition(read_jsonl(ctx.canonical), load_split_assignments(ctx.splits))
    for split in ("train", "val"):
        small = resized_copy(parts[split], ctx.images_root, work / "images", max_side=int(opts["max_side"]))
        write_coco_layout(small, data_dir, layout="yolox", split=split, images_root=work / "images", link=True)
    out_dir = Path(str(opts["output_dir"]))
    exp_dir = out_dir / EXP_NAME
    exp_dir.mkdir(parents=True, exist_ok=True)
    exp_path = ctx.run_dir / f"{EXP_NAME}.py"
    exp_path.write_text(render_exp(ctx, data_dir, opts), encoding="utf-8")
    resume = find_resume_checkpoint(resume_candidates(opts)) if opts.get("resume", "auto") == "auto" else None
    carried: list[str] = []
    if resume is not None:
        if checkpoint_epoch(resume) is None:
            raise RuntimeError(f"resume checkpoint {resume} is unreadable; detach that input or set resume: off")
        carried = copy_resume_files(resume, exp_dir)
        resume = exp_dir / "latest_ckpt.pth"
    else:
        stale = clear_stale_checkpoints(exp_dir)
        if stale:
            print(f"fresh run: removed checkpoints of an earlier run in {exp_dir}: {stale}", flush=True)
    log = exp_dir / "train_log.txt"
    budget = opts.get("time_budget_h")
    budget_s = None if budget is None else float(budget) * 3600
    started = time.time()
    max_epoch = int(ctx.cfg["train"]["epochs"])
    latest = exp_dir / "latest_ckpt.pth"
    cmd: list[str] = []

    def run_once(attempt: int) -> tuple[str, bool, int | None]:
        nonlocal resume, cmd
        run_opts = dict(opts)
        if attempt > 0:  # after a hang: fewer DataLoader workers, continue from the last epoch checkpoint
            run_opts["workers"] = min(int(opts["workers"]), (2, 1)[min(attempt, 2) - 1])
            resume = latest if checkpoint_epoch(latest) is not None else None
            print(f"restart {attempt}: workers={run_opts['workers']}, resume={'latest_ckpt.pth' if resume else 'from scratch'}", flush=True)
        exp_path.write_text(render_exp(ctx, data_dir, run_opts), encoding="utf-8")
        cmd = build_command(exp_path, ctx, run_opts, resume=resume, launcher=os.environ.get(LAUNCHER_ENV) or None)
        env = train_environment(os.environ, repo, int(opts["devices"]))
        offset = max(0, _log_size(log))
        remaining = None if budget_s is None else max(60.0, budget_s - (time.time() - started))
        print("$", " ".join(cmd), f"(cwd {repo})", flush=True)
        rc, stopped = run_with_budget(cmd, cwd=repo, env=env, budget_s=remaining, watch=latest,
                                      grace_s=float(opts.get("stop_grace_s", 1800)), log=log, stall_s=float(opts["stall_s"]))
        errors = caught_errors(log, offset)
        epoch = checkpoint_epoch(latest)
        return outcome(rc=rc, stopped=stopped, errors=errors, epoch=epoch, max_epoch=max_epoch), stopped, epoch

    (status, stopped, epoch), restarts = supervise(run_once, max_restarts=int(opts["max_restarts"]))
    best = exp_dir / "best_ckpt.pth"
    if best.is_file() and checkpoint_epoch(best) is None:  # stopped during the best-checkpoint copy
        best.unlink()
    return {"command": cmd, "exp_file": str(exp_path), "status": status, "resumed_from": None if resume is None else str(resume),
            "resume_files_copied": carried, "epochs_done": epoch, "max_epoch": max_epoch, "devices": int(opts["devices"]),
            "stopped_for_time_budget": stopped, "restarts": restarts, "hours": round((time.time() - started) / 3600, 3), "checkpoint_dir": str(exp_dir),
            "best_ckpt": str(best), "latest_ckpt": str(exp_dir / "latest_ckpt.pth"),
            "note": "Export with trainers.yolox_adapter.export_onnx (decode_in_inference=False). best_ckpt.pth is "
                    "written only when val AP50:95 improves (absent after a 1-2 epoch smoke run -> use latest)."}


def export_onnx(exp_file: Path, ckpt: Path, out: Path, *, opset: int = 13, raw_logits: bool = True) -> dict[str, Any]:  # pragma: no cover
    """YOLOX checkpoint -> ONNX with RAW head output [1, N, 5+C], no grid decode; with ``raw_logits`` (default)
    obj/cls are logits (config ``decode.sigmoid_applied: false``). The app decodes per DECODE_SPEC §3.1.
    Mirrors YOLOX tools/export_onnx.py without --decode_in_inference. Needs torch + YOLOX + onnx."""
    torch = require("torch", "pip install torch")
    require("yolox", INSTALL_HINT)
    from torch import nn
    from yolox.exp import get_exp
    from yolox.models.network_blocks import SiLU
    from yolox.utils import replace_module

    exp = get_exp(str(exp_file), None)
    model = exp.get_model()
    state = torch.load(str(ckpt), map_location="cpu", weights_only=False)  # own/YOLOX ckpt (numpy scalars; torch>=2.6 default)
    model.load_state_dict(state.get("model", state))
    model = replace_module(model, nn.SiLU, SiLU)  # export-friendly SiLU, as upstream export_onnx.py
    model.head.decode_in_inference = False
    model.eval()
    h, w = exp.test_size
    dummy = torch.zeros(1, 3, h, w)
    out.parent.mkdir(parents=True, exist_ok=True)
    torch.onnx.export(model, dummy, str(out), input_names=["images"], output_names=["output"], opset_version=opset, dynamo=False)
    with torch.no_grad():
        shape = list(model(dummy).shape)
    stripped = strip_head_sigmoid(out) if raw_logits else 0
    if raw_logits and stripped != 2 * len(model.head.strides):
        raise RuntimeError(f"expected {2 * len(model.head.strides)} head Sigmoid nodes (obj+cls per level), stripped {stripped}")
    return {"onnx": str(out), "input": [1, 3, h, w], "output_shape": shape, "opset": opset, "act": getattr(exp, "act", "silu"),
            "head_sigmoid_stripped": stripped, "sigmoid_applied": not raw_logits}


def strip_head_sigmoid(onnx_path: Path) -> int:  # pragma: no cover - needs onnx (proven on a tiny graph, see WEIGHT_LICENSES §3.1)
    """Remove the YOLOX head's obj/cls Sigmoid nodes (those consumed ONLY by Concat) so the model outputs raw
    logits (labels.json ``sigmoid_applied: false``; the app applies the sigmoid, DECODE_SPEC §3.1).

    Why: onnx2tf 2.6.9's default flatbuffer_direct INT8 path rejects LOGISTIC outputs whose calibrated scale is
    not 1/256 (proven locally 2026-10-10), and probabilities share one int8 scale with box offsets in the raw
    tensor. SiLU's Sigmoid nodes feed Mul and are left untouched."""
    onnx = require("onnx", "pip install onnx")
    model = onnx.load(str(onnx_path))
    g = model.graph
    consumers: dict[str, list[Any]] = {}
    for n in g.node:
        for i in n.input:
            consumers.setdefault(i, []).append(n)
    outputs = {o.name for o in g.output}
    drop = [n for n in g.node if n.op_type == "Sigmoid" and n.output[0] not in outputs
            and consumers.get(n.output[0]) and all(c.op_type == "Concat" for c in consumers[n.output[0]])]
    for n in drop:
        for c in consumers[n.output[0]]:
            for k, name in enumerate(c.input):
                if name == n.output[0]:
                    c.input[k] = n.input[0]
        g.node.remove(n)
    onnx.checker.check_model(model)
    onnx.save(model, str(onnx_path))
    return len(drop)


def expected_rows(input_size: Sequence[int], strides: Sequence[int] = (8, 16, 32)) -> int:
    w, h = input_size
    return sum((w // s) * (h // s) for s in strides)
